package com.bcnf.sql;

import com.bcnf.exception.BCNFViolationException;
import com.bcnf.model.FunctionalDependency;
import com.bcnf.model.Relation;

import java.util.ArrayList;
import java.util.List;

/**
 * Generates standard SQL DDL scripts to repair a BCNF violation by decomposing
 * the original table into two (or more) tables that are in BCNF.
 *
 * <p>For a violating FD X -> Y, this generator produces:</p>
 * <ol>
 *   <li>CREATE TABLE for R1(X, Y)</li>
 *   <li>CREATE TABLE for R2(X, remaining attributes)</li>
 *   <li>INSERT statements to migrate data from the original table</li>
 *   <li>DROP TABLE for the original relation (optional)</li>
 * </ol>
 *
 * @author BCNF Violation Exception Handler (Group-29)
 * @since 1.0
 */
public final class BCNFSQLGenerator {

    private BCNFSQLGenerator() {
        // utility class - prevent instantiation
    }

    /**
     * Generates a complete refactoring script to decompose a relation according
     * to the violating functional dependency carried in the exception.
     *
     * @param ex the exception containing the violation details
     * @return a multi-statement SQL script as a single string
     */
    public static String generateRefactoringScript(BCNFViolationException ex) {
        Relation relation = ex.getRelation();
        FunctionalDependency violatingFD = ex.getViolatingDependency();

        List<String> statements = new ArrayList<>();

        statements.add("-- BCNF Refactoring Script");
        statements.add("-- Generated by BCNF Violation Exception Handler (Group-29)");
        statements.add("-- Original relation: " + relation);
        statements.add("-- Violating FD: " + violatingFD);
        statements.add("");

        String originalName = relation.getName();
        String r1Name = originalName + "_1";
        String r2Name = originalName + "_2";

        // R1 attributes = determinant + consequent
        String r1Attrs = buildAttributeList(violatingFD.getDeterminant(), violatingFD.getConsequent());
        // R2 attributes = determinant + (all - consequent)
        String r2Attrs = buildAttributeList(
                violatingFD.getDeterminant(),
                relation.getAttributes().stream()
                        .filter(a -> !violatingFD.getConsequent().contains(a))
                        .toList()
        );

        // CREATE R1
        statements.add("CREATE TABLE " + r1Name + " (");
        statements.add("    " + r1Attrs.replace(", ", ",\n    ") + ",\n    PRIMARY KEY (" + String.join(", ", violatingFD.getDeterminant()) + ")");
        statements.add(");");
        statements.add("");

        // CREATE R2
        statements.add("CREATE TABLE " + r2Name + " (");
        statements.add("    " + r2Attrs.replace(", ", ",\n    ") + ",\n    PRIMARY KEY (" + String.join(", ", violatingFD.getDeterminant()) + ")");
        statements.add(");");
        statements.add("");

        // INSERT data into R1
        statements.add("-- Migrate data into decomposed tables");
        statements.add("INSERT INTO " + r1Name + " (" + r1Attrs + ")");
        statements.add("SELECT DISTINCT " + r1Attrs + " FROM " + originalName + ";");
        statements.add("");

        // INSERT data into R2
        String r2Cols = r2Attrs.replace(", ", ", ");
        statements.add("INSERT INTO " + r2Name + " (" + r2Cols + ")");
        statements.add("SELECT DISTINCT " + r2Cols + " FROM " + originalName + ";");
        statements.add("");

        // Optional: drop original table (commented for safety)
        statements.add("-- Uncomment the next line after verifying data migration");
        statements.add("-- DROP TABLE " + originalName + ";");

        return String.join("\n", statements);
    }

    /**
     * Builds a comma-separated attribute list from two attribute sets.
     */
    private static String buildAttributeList(Iterable<String> first, Iterable<String> second) {
        List<String> combined = new ArrayList<>();
        for (String s : first) combined.add(s);
        for (String s : second) if (!combined.contains(s)) combined.add(s);
        return String.join(", ", combined);
    }

    /**
     * Generates a verification query to test the decomposition.
     */
    public static String generateVerificationQuery(BCNFViolationException ex) {
        Relation relation = ex.getRelation();
        String originalName = relation.getName();
        String r1Name = originalName + "_1";
        String r2Name = originalName + "_2";

        return """
                -- Verification: check lossless join
                SELECT COUNT(*) AS original_rows FROM %s;
                SELECT COUNT(*) AS joined_rows
                FROM %s r1 NATURAL JOIN %s r2;
                -- If counts match, the decomposition is lossless.
                """.formatted(originalName, r1Name, r2Name);
    }
}